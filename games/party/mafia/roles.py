def build_roles(n: int, disabled=()):
    ok = lambda r: r not in disabled
    m = 1 if n < 7 else 2 if n < 10 else 3 if n < 14 else 4
    roles = []
    if n >= 6 and ok("don"):
        roles.append("don")
    seq = ["mafia", "lawyer", "killer", "journalist", "mafia"]
    for r in seq:
        if len(roles) >= m:
            break
        if r == "lawyer" and (m < 3 or not ok(r)):
            r = "mafia"
        if r in ("killer", "journalist") and (m < 4 or not ok(r)):
            r = "mafia"
        roles.append(r)
    roles = roles[:m]
    for r, min_n in PRIORITY:
        if len(roles) >= n:
            break
        if n >= min_n and ok(r):
            roles.append(r)
    while len(roles) < n:
        roles.append("citizen")
    return roles[:n]
